-- MBFinance: skema ringan untuk keuangan Bryan & Maddy.
-- Semua nominal memakai Rupiah tanpa desimal (BIGINT), misalnya 150000 = Rp150.000.
-- Jalankan file ini sekali di Supabase SQL Editor atau sebagai migration Supabase CLI.

create table public.people (
  id bigint generated by default as identity primary key,
  name text not null unique,
  is_custodian boolean not null default false,
  auth_user_id uuid unique references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  constraint people_name_not_blank check (char_length(trim(name)) > 0)
);

-- Rekening, kas, e-wallet, dan tabungan yang menyimpan uang bersama.
-- "Uang Bryan" dipakai saat Maddy mentransfer uang untuk dipegang Bryan sementara.
create table public.accounts (
  id bigint generated by default as identity primary key,
  name text not null unique,
  account_type text not null default 'bank'
    check (account_type in ('cash', 'bank', 'e_wallet', 'savings', 'other')),
  -- holder = siapa yang secara fisik memegang/mengelola uang;
  -- owner = pemilik dana pribadi. owner null berarti dana milik bersama.
  holder_id bigint references public.people (id) on delete set null,
  owner_person_id bigint references public.people (id) on delete restrict,
  is_shared boolean not null default true,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint accounts_name_not_blank check (char_length(trim(name)) > 0),
  constraint accounts_owner_matches_shared_status check (
    (is_shared and owner_person_id is null)
    or (not is_shared and owner_person_id is not null)
  )
);

-- Satu buku kas untuk semua arus uang.
-- income: dari luar -> rekening; expense/bill: rekening -> luar;
-- transfer/saving: antar rekening. Saldo selalu dihitung dari tabel ini.
create table public.ledger_entries (
  id bigint generated by default as identity primary key,
  entry_date date not null default current_date,
  entry_type text not null
    check (entry_type in ('income', 'expense', 'bill', 'transfer', 'saving', 'adjustment')),
  category text not null default 'other'
    check (category in ('daily', 'personal', 'shopee', 'application', 'savings', 'transfer', 'other')),
  amount bigint not null check (amount > 0),
  from_account_id bigint references public.accounts (id) on delete restrict,
  to_account_id bigint references public.accounts (id) on delete restrict,
  used_by_person_id bigint references public.people (id) on delete set null,
  note text,
  created_at timestamptz not null default now(),
  constraint ledger_has_an_account check (from_account_id is not null or to_account_id is not null),
  constraint ledger_accounts_are_different check (
    from_account_id is null or to_account_id is null or from_account_id <> to_account_id
  )
);

create index ledger_entries_entry_date_idx on public.ledger_entries (entry_date desc);
create index ledger_entries_used_by_date_idx on public.ledger_entries (used_by_person_id, entry_date desc);
create index ledger_entries_from_account_idx on public.ledger_entries (from_account_id);
create index ledger_entries_to_account_idx on public.ledger_entries (to_account_id);

-- Definisi tagihan berulang. Nilai tagihan dapat diubah per bulan pada bill_instances.
create table public.recurring_bills (
  id bigint generated by default as identity primary key,
  name text not null,
  bill_category text not null
    check (bill_category in ('personal', 'shopee', 'application', 'other')),
  responsible_person_id bigint references public.people (id) on delete set null,
  default_source_account_id bigint references public.accounts (id) on delete set null,
  default_amount bigint not null check (default_amount > 0),
  due_day smallint check (due_day between 1 and 31),
  is_active boolean not null default true,
  note text,
  created_at timestamptz not null default now(),
  constraint recurring_bills_name_not_blank check (char_length(trim(name)) > 0)
);

-- Baris tagihan untuk satu bulan. Tidak ada tagihan yang dibuat otomatis tersembunyi;
-- panggil fungsi create_bill_instances saat awal bulan.
create table public.bill_instances (
  id bigint generated by default as identity primary key,
  recurring_bill_id bigint not null references public.recurring_bills (id) on delete cascade,
  bill_month date not null,
  amount_due bigint not null check (amount_due > 0),
  status text not null default 'pending' check (status in ('pending', 'paid', 'skipped')),
  paid_on date,
  payment_entry_id bigint unique references public.ledger_entries (id) on delete restrict,
  note text,
  created_at timestamptz not null default now(),
  unique (recurring_bill_id, bill_month),
  constraint bill_instances_month_is_first_day check (bill_month = date_trunc('month', bill_month)::date),
  constraint bill_instances_payment_matches_status check (
    (status = 'paid' and paid_on is not null and payment_entry_id is not null)
    or (status in ('pending', 'skipped') and paid_on is null and payment_entry_id is null)
  )
);

create index bill_instances_month_idx on public.bill_instances (bill_month desc, status);

create table public.savings_goals (
  id bigint generated by default as identity primary key,
  name text not null,
  target_amount bigint not null check (target_amount > 0),
  target_date date,
  is_active boolean not null default true,
  note text,
  created_at timestamptz not null default now(),
  constraint savings_goals_name_not_blank check (char_length(trim(name)) > 0)
);

-- Setiap setoran ke target harus merujuk ke satu perpindahan ledger ke rekening tabungan.
create table public.savings_contributions (
  id bigint generated by default as identity primary key,
  goal_id bigint not null references public.savings_goals (id) on delete cascade,
  ledger_entry_id bigint not null unique references public.ledger_entries (id) on delete restrict,
  contributed_by_person_id bigint references public.people (id) on delete set null,
  amount bigint not null check (amount > 0),
  created_at timestamptz not null default now()
);

create index savings_contributions_goal_idx on public.savings_contributions (goal_id);

