-- Membuat daftar tagihan bulan tertentu dari recurring_bills yang masih aktif.
create or replace function public.create_bill_instances(p_month date)
returns integer
language plpgsql
set search_path = public
as $$
declare
  inserted_count integer;
begin
  if p_month <> date_trunc('month', p_month)::date then
    raise exception 'p_month harus tanggal pertama dalam bulan tersebut';
  end if;

  insert into public.bill_instances (recurring_bill_id, bill_month, amount_due)
  select id, p_month, default_amount
  from public.recurring_bills
  where is_active
  on conflict (recurring_bill_id, bill_month) do nothing;

  get diagnostics inserted_count = row_count;
  return inserted_count;
end;
$$;

-- Saldo per rekening. Transfer tidak mengubah total uang bersama, hanya berpindah tempat.
create or replace view public.v_account_balances
with (security_invoker = true) as
select
  a.id,
  a.name,
  a.account_type,
  a.holder_id,
  p.name as holder_name,
  p.is_custodian as holder_is_custodian,
  a.owner_person_id,
  owner.name as owner_name,
  owner.is_custodian as owner_is_custodian,
  a.is_shared,
  a.is_active,
  coalesce(sum(case when l.to_account_id = a.id then l.amount else 0 end), 0)
    - coalesce(sum(case when l.from_account_id = a.id then l.amount else 0 end), 0) as balance
from public.accounts a
left join public.people p on p.id = a.holder_id
left join public.people owner on owner.id = a.owner_person_id
left join public.ledger_entries l on l.from_account_id = a.id or l.to_account_id = a.id
group by a.id, p.name, p.is_custodian, owner.name, owner.is_custodian;

-- Total gabungan mencakup dana bersama + dana pribadi Bryan + dana pribadi Maddy.
-- Sementara total_shared_money hanya menunjukkan dana yang benar-benar milik bersama.
create or replace view public.v_shared_overview
with (security_invoker = true) as
select
  coalesce(sum(balance), 0) as total_combined_money,
  coalesce(sum(balance) filter (where is_shared), 0) as total_shared_money,
  coalesce(sum(balance) filter (where not is_shared and owner_name = 'Bryan'), 0) as bryan_personal_money,
  coalesce(sum(balance) filter (where not is_shared and owner_name = 'Maddy'), 0) as maddy_personal_money,
  coalesce(sum(balance) filter (where holder_is_custodian), 0) as total_held_by_maddy,
  coalesce(sum(balance) filter (where not coalesce(holder_is_custodian, false)), 0) as total_held_by_others,
  coalesce(sum(balance) filter (where is_shared and holder_is_custodian), 0) as shared_money_held_by_maddy,
  coalesce(sum(balance) filter (where is_shared and not coalesce(holder_is_custodian, false)), 0) as shared_money_held_by_others,
  coalesce(sum(balance) filter (where account_type = 'savings'), 0) as total_savings
from public.v_account_balances;

-- Pemakaian per orang per bulan, termasuk pembayaran tagihan yang diberi used_by_person_id.
create or replace view public.v_person_monthly_usage
with (security_invoker = true) as
select
  date_trunc('month', l.entry_date)::date as month,
  p.id as person_id,
  p.name as person_name,
  coalesce(sum(l.amount) filter (where l.category = 'daily'), 0) as daily_usage,
  coalesce(sum(l.amount) filter (where l.category = 'personal'), 0) as personal_usage,
  coalesce(sum(l.amount) filter (where l.category = 'shopee'), 0) as shopee_usage,
  coalesce(sum(l.amount) filter (where l.category = 'application'), 0) as application_usage,
  coalesce(sum(l.amount), 0) as total_usage
from public.ledger_entries l
join public.people p on p.id = l.used_by_person_id
where l.entry_type in ('expense', 'bill')
group by 1, p.id, p.name;

-- Arus uang dan pemakaian total bulanan. saving_added adalah perpindahan ke rekening tabungan.
create or replace view public.v_monthly_cashflow
with (security_invoker = true) as
select
  date_trunc('month', entry_date)::date as month,
  coalesce(sum(amount) filter (where entry_type = 'income'), 0) as money_in,
  coalesce(sum(amount) filter (where entry_type in ('expense', 'bill')), 0) as total_usage,
  coalesce(sum(amount) filter (where category = 'daily' and entry_type in ('expense', 'bill')), 0) as daily_usage,
  coalesce(sum(amount) filter (where category = 'personal' and entry_type in ('expense', 'bill')), 0) as personal_usage,
  coalesce(sum(amount) filter (where category = 'shopee' and entry_type in ('expense', 'bill')), 0) as shopee_usage,
  coalesce(sum(amount) filter (where category = 'application' and entry_type in ('expense', 'bill')), 0) as application_usage,
  coalesce(sum(amount) filter (where entry_type = 'bill'), 0) as bills_paid,
  coalesce(sum(amount) filter (where entry_type = 'saving'), 0) as saving_added
from public.ledger_entries
group by 1;

-- Total tagihan yang harus dibayar dan yang sudah dibayar per bulan.
create or replace view public.v_monthly_bill_summary
with (security_invoker = true) as
select
  bill_month,
  coalesce(sum(amount_due), 0) as total_due,
  coalesce(sum(amount_due) filter (where status = 'paid'), 0) as total_paid,
  coalesce(sum(amount_due) filter (where status = 'pending'), 0) as total_pending,
  count(*) filter (where status = 'pending') as pending_count
from public.bill_instances
group by bill_month;

-- Progres setiap target tabungan. saldo_tabungan tetap terlihat di v_shared_overview.
create or replace view public.v_savings_goal_progress
with (security_invoker = true) as
select
  g.id,
  g.name,
  g.target_amount,
  g.target_date,
  g.is_active,
  coalesce(sum(c.amount), 0) as saved_amount,
  greatest(g.target_amount - coalesce(sum(c.amount), 0), 0) as remaining_amount,
  round(coalesce(sum(c.amount), 0)::numeric / g.target_amount * 100, 2) as progress_percent
from public.savings_goals g
left join public.savings_contributions c on c.goal_id = g.id
group by g.id;

